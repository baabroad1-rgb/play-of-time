package online.playoftime.core.utils

/** Тип результата последней попытки — определяет цвет фона кнопки */
enum class ButtonResultType {
    NONE,       // нет результата (старт или идёт таймер)
    EARLY,      // остановка раньше цели → красный фон
    LATE,       // остановка позже цели → синий фон
    TRUE_THREE, // точное попадание → зелёный фон
    // Победа по смягчению (в допуске, не ровно 3) → блёклый зелёный (Alex 2026-11-03),
    // со стороны своей ошибки: раньше 3 — чуть краснее, позже — чуть синее (Alex 2026-11-08).
    EASED_EARLY,
    EASED_LATE
}
